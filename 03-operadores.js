let num1 = 10;
let num2 = 20;

// Operaciones básicas aritméticas
const addResult = num1 + num2;
console.log('Addition result:', addResult);

const subResult = num1 - num2;
console.log('Subtraction result:', subResult);

const multiplyResult = num1 * num2;
console.log('Multiply result:', multiplyResult);

const divideResult = num2 / num1;
console.log('Division result:', divideResult);

// Operadores de asignación (Todo esto se aplica al resto de signos aritméticos)
num1 = num1 + 5; //Aumenta el número en 5
console.log('num1:', num1);

num1 += 5; //Forma reducida de aumentar el número en 5
console.log('num1:', num1);

num1++; //Aumenta el número en 1
console.log('num1:', num1);

const moduleResult = 10 % 2; //Te muestra el resto de una división
console.log('El resto de la división es de:', moduleResult);

const moduleResult2 = 10 % 3;
console.log('El resto de la división es de:', moduleResult2);
